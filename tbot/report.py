_W, _H = 920, 280
_PAD_L, _PAD_R, _PAD_T, _PAD_B = 62, 16, 16, 30


def _scale(vals, lo, hi, out_lo, out_hi):
    span = (hi - lo) or 1.0
    return [out_lo + (v - lo) / span * (out_hi - out_lo) for v in vals]


def _line_chart(dates, values, color_var, fill=False, money=True, invert=False):
    """One series, one axis. Returns (svg, points_json)."""
    n = len(values)
    if n < 2:
        return "<p>Not enough data to plot.</p>", "[]"

    lo, hi = min(values), max(values)
    pad = (hi - lo) * 0.08 or 1.0
    lo, hi = lo - pad, hi + pad
    if invert:
        # Drawdown tops out at zero by definition, so do not pad above it.
        hi = 0.0

    xs = _scale(range(n), 0, n - 1, _PAD_L, _W - _PAD_R)
    ys = _scale(values, lo, hi, _H - _PAD_B, _PAD_T)

    pts = " ".join(f"{x:.2f},{y:.2f}" for x, y in zip(xs, ys))
    base_y = _scale([lo if not invert else 0.0], lo, hi, _H - _PAD_B, _PAD_T)[0]

    area = ""
    if fill:
        area = (f'<polygon points="{xs[0]:.2f},{base_y:.2f} {pts} '
                f'{xs[-1]:.2f},{base_y:.2f}" fill="var({color_var})" opacity="0.14"/>')

    # Gridlines and y ticks: five steps, recessive.
    grid, ticks = [], []
    for k in range(5):
        v = lo + (hi - lo) * k / 4
        y = _scale([v], lo, hi, _H - _PAD_B, _PAD_T)[0]
        grid.append(f'<line x1="{_PAD_L}" y1="{y:.1f}" x2="{_W - _PAD_R}" y2="{y:.1f}" '
                    f'stroke="var(--gridline)" stroke-width="1"/>')
        label = f"${v:,.0f}" if money else f"{v * 100:.0f}%"
        ticks.append(f'<text x="{_PAD_L - 8}" y="{y + 4:.1f}" text-anchor="end" '
                     f'class="tick">{label}</text>')

    # X labels: first, middle, last. The outer two anchor inward so they do
    # not run off the edge of the plot.
    xlab = []
    for k, anchor in ((0, "start"), (n // 2, "middle"), (n - 1, "end")):
        xlab.append(f'<text x="{xs[k]:.1f}" y="{_H - 8}" text-anchor="{anchor}" '
                    f'class="tick">{dates[k]}</text>')

    svg = f"""<svg viewBox="0 0 {_W} {_H}" class="chart" role="img" preserveAspectRatio="none">
  {''.join(grid)}
  {area}
  <polyline points="{pts}" fill="none" stroke="var({color_var})" stroke-width="2"
            stroke-linejoin="round" stroke-linecap="round" vector-effect="non-scaling-stroke"/>
  {''.join(ticks)}{''.join(xlab)}
  <line class="crosshair" x1="0" y1="{_PAD_T}" x2="0" y2="{_H - _PAD_B}"
        stroke="var(--muted)" stroke-width="1" stroke-dasharray="3 3" opacity="0"/>
  <circle class="cursor-dot" r="4" fill="var({color_var})" stroke="var(--surface-1)"
          stroke-width="2" opacity="0"/>
</svg>"""

    payload = json.dumps([
        {"x": round(x, 2), "y": round(y, 2), "d": d, "v": v}
        for x, y, d, v in zip(xs, ys, dates, values)
    ])
    return svg, payload


def _tile(label, value, sub="", tone=""):
    cls = f"tile {tone}".strip()
    return (f'<div class="{cls}"><div class="tile-label">{label}</div>'
            f'<div class="tile-value">{value}</div>'
            f'<div class="tile-sub">{sub}</div></div>')


