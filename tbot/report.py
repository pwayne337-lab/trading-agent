def trade_card(sym: str, order, signal, trend: dict) -> str:
    """One trade idea, formatted so you can act on it or reject it in 10 seconds."""
    lines = [
        f"### {sym}",
        "",
        f"| | |",
        f"|---|---|",
        f"| Entry (market on open) | ~${order.entry:,.2f} |",
        f"| Stop | ${order.stop:,.2f} |",
        f"| Target (2R) | ${order.target:,.2f} |",
        f"| Shares | {order.shares} |",
        f"| Position size | ${order.notional:,.2f} ({order.pct_of_equity:.1f}% of account) |",
        f"| If the stop hits, you lose | ${order.dollars_at_risk:,.2f} |",
        f"| Risk per share | ${order.risk_per_share:,.2f} |",
        "",
        f"Setup: closed at ${trend.get('close', 0):,.2f}, "
        f"{trend.get('pct_from_ema', 0):+.2f}% from the 20 EMA "
        f"(${trend.get('ema_pb', 0):,.2f}). "
        f"50 SMA ${trend.get('sma_fast', 0):,.2f} above 200 SMA ${trend.get('sma_slow', 0):,.2f}. "
        f"ATR ${trend.get('atr', 0):,.2f}. {signal.notes}.",
        "",
    ]
    return "\n".join(lines)


def signal_report(cards: List[str], rejected: List[str], equity: float,
                  scanned: int, as_of, cfg) -> str:
    stamp = pd.Timestamp(as_of).date() if as_of is not None else datetime.now().date()
    head = [
        f"# Trade signals for {stamp}",
        "",
        f"Scanned {scanned} symbols. Account equity used for sizing: ${equity:,.2f}. "
        f"Risking {cfg.risk.risk_per_trade * 100:.2f}% per trade.",
        "",
        "These are generated by fixed rules, not by judgment. Rules do not know "
        "about earnings dates, Fed days, or anything that happened in the news. "
        "Read each one before you act on it.",
        "",
    ]
    if not cards:
        head += ["**No setups today.** Nothing on the watchlist met every condition. "
                 "Most days look like this. Taking a trade because you want one is "
                 "how a rule-based system quietly turns into a discretionary one.", ""]
    else:
        head += [f"## {len(cards)} setup(s)", ""] + cards

    if rejected:
        head += ["## Signals that fired but were not sized", ""]
        head += [f"- {r}" for r in rejected]
        head += [""]

    head += [
        "---",
        "",
        "Entries assume a market order at the next session's open. You will not "
        "get the exact price shown. Size off your actual fill, not off this estimate.",
    ]
    return "\n".join(head)


def write_signal_report(text: str, as_of=None) -> Path:
    stamp = pd.Timestamp(as_of).date() if as_of is not None else datetime.now().date()
    path = REPORTS / f"signals_{stamp}.md"
    path.write_text(text)
    return path


